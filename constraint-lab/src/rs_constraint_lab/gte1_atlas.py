"""Behaviour atlas for GT Round E1 (GT-P004).

Every item of the frozen plan appears, whatever its status: the 32 authorised
cells and the 16 baseline re-derivations. Values are exact-kernel channels
from the published tables; nothing is selected or weighted. Conditionals on
rare mass (< 1e-12) are marked † and are not interpreted; low mass
(< 1e-6) is marked ‡.

    python -m rs_constraint_lab.gte1_atlas
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from rs_constraint_lab import gte1

TABLES = gte1.TABLES_RELPATH
OUT = "gravity-time/reports/gt-e1-atlas.md"
CELL_ORDER = [(5, "W4"), (5, "W3"), (5, "W16"), (6, "W4"), (6, "W3"), (6, "W16"), (7, "W4")]


def _f(value, digits: int = 3) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != 0 and (abs(value) < 1e-3 or abs(value) >= 1e4):
            return f"{value:.1e}"
        return f"{value:+.{digits}f}" if value < 0 else f"{value:.{digits}f}"
    return str(value)


def _m(value) -> str:
    """Signed margin-style value."""
    if value is None:
        return "—"
    if value != 0 and abs(value) < 1e-3:
        return f"{value:+.1e}"
    return f"{value:+.3f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"] + ["| " + " | ".join(r) + " |" for r in rows]


PROFILE_TABLES = (
    ("Attachment (r0 = size-specific null ceiling)", [
        ("r0", "null_attachment_fraction", _f), ("af c", "attachment_fraction_ct", _f), ("af j", "attachment_fraction_jump", _f),
        ("raw c", "margin_raw_ct", _m), ("raw j", "margin_raw_jump", _m), ("norm c", "margin_normalised_ct", _m), ("norm j", "margin_normalised_jump", _m),
        ("std c", "margin_standardised_ct", _m), ("std j", "margin_standardised_jump", _m),
    ]),
    ("Circulation and event order", [
        ("irr", "irreversible_flux_fraction", _f), ("σ/event", "entropy_production_per_event", _f), ("max aff", "max_square_affinity", _f),
        ("A₂", "event_order_asymmetry", _f), ("H adj", "handover_index_adjacent", _m), ("H all", "handover_index_all", _m), ("fwd steps", "handover_forward_oriented_adjacent_steps", _f),
        ("A₂ʰ", "hub_frame_asymmetry", _f), ("rev", "immediate_reversal_probability", _f),
    ]),
    ("Occupancy, detachment and hubs", [
        ("E", "expected_edges", _f), ("dens c", "free_edge_density_ct", _f), ("dens j", "free_edge_density_jump", _f),
        ("det c", "detached_fraction_ct", _f), ("det j", "detached_fraction_jump", _f), ("capture c", "capture_rate_when_detached_ct", _f),
        ("ρ c", "near_far_ratio_ct", _f), ("ρ j", "near_far_ratio_jump", _f), ("hub∋src", "hub_includes_source", _f), ("hub probe-only", "hub_probe_only", _f),
    ]),
    ("Persistence (integrated autocorrelation times; events = mean-event units)", [
        ("τ att (t)", "tau_attached_probe_time", _f), ("τ att (ev)", "tau_attached_probe_events", _f), ("τ det (ev)", "tau_detached_probe_events", _f),
        ("τ free (ev)", "tau_free_edges_events", _f), ("τ deg (ev)", "tau_degree_probe_events", _f), ("L", "localisation_persistence_index", _f), ("mean rate", "mean_rate_ct", _f),
    ]),
)


def build(repo: Path, tables: Path | None = None, plan_path: Path | None = None) -> str:
    t = json.loads((tables or repo / TABLES).read_text())
    plan = json.loads((plan_path or repo / gte1.PLAN_RELPATH).read_text())
    results, records, profiles = t["results"], t["item_records"], t["behaviour_profiles"]
    rare = t["rare_mass_flags"]
    lines = [
        "# GT-E1 behaviour atlas",
        "",
        f"Generated by `rs_constraint_lab.gte1_atlas` from `{TABLES}` (payload `{t['payload_sha256'][:12]}…`), frozen plan `{t['frozen_analysis_plan_commit'][:7]}` (hash `{t['plan_hash'][:12]}…`). Every item of the plan is listed. Values are exact-kernel channels; no score is formed and no cell is omitted. Clocks: c = continuous (per unit time), j = jump chain (per event). The generator spectrum is **unavailable** in every cell (not zero): gtobs does not form the dense generator.",
        "",
        "Cells: N5/N6 W4 rows are in-round re-derivations of published E0B cells (not new observations). N5/N6 W3 and W16 rows are tranche II. N7 W4 rows are tranche I. NULL N7 was previously evaluated as a fixture.",
        "",
        "## 1. Item records",
        "",
    ]
    rows = []
    for it in plan["items"]:
        rec = records[it["item_id"]]
        flags = rare.get(it["item_id"], {"rare": [], "low": []})
        rows.append([it["item_id"], it["tranche"], it["role"], rec["status"], _f(rec["wall_seconds"], 1), _f(rec["peak_rss_mb"], 0), "; ".join(rec["numerical_problems"] or []) or ("—" if rec["numerical_problems"] is None else "none"), f"{len(flags['rare'])} / {len(flags['low'])}"])
    lines += _table(["Item", "Tranche", "Role", "Status", "Wall s", "Peak MB", "Numerical problems", "Rare / low conditionals"], rows)
    lines += ["", f"Status counts: {t['status_counts']}. Longest cell {_f(t['wall_seconds_max'], 1)} s; sum over cells {_f(t['wall_seconds_total_cpu_cells'], 0)} s.", ""]

    lines += ["## 2. Behaviour profiles by family", ""]
    for family in gte1.FAMILY_ORDER:
        lines += [f"### {family} `{gte1.grade_of(family)}`", ""]
        cells = [(n, a) for n, a in CELL_ORDER if gte1.item_id(n, a, family) in records]
        for title, cols in PROFILE_TABLES:
            body = []
            for n, a in cells:
                p = profiles.get(gte1.item_id(n, a, family))
                if p is None:
                    body.append([f"N{n} {a}"] + [records[gte1.item_id(n, a, family)]["status"]] + ["—"] * (len(cols) - 1))
                else:
                    body.append([f"N{n} {a}"] + [fmt(p.get(key)) for _, key, fmt in cols])
            lines += [f"*{title}*", ""] + _table(["Cell"] + [c[0] for c in cols], body) + [""]

    lines += ["## 3. Attachment by free-edge count (a/k), N7 cells, both clocks", "", "Each entry is E[a | k] / k with the probability of k in brackets; † rare (< 1e-12), ‡ low (< 1e-6). Null: r0 = 0.667 at every k.", ""]
    for family in gte1.FAMILY_ORDER:
        r = results.get(gte1.item_id(7, "W4", family))
        if not r or "held_continuous" not in r:
            continue
        for key, label in (("held_continuous", "c"), ("held_jump", "j")):
            h = r[key]
            entries = []
            for k, v in h["attachment_fraction_by_free_edge_count"].items():
                if v is None:
                    continue
                mass = h["free_edge_count_distribution"][k]
                mark = "†" if mass < gte1.RARE_MASS_FLOOR else ("‡" if mass < gte1.LOW_MASS_FLOOR else "")
                entries.append(f"k{k}: {v:.3f} ({mass:.1e}){mark}")
            lines.append(f"- **{family} {label}:** " + "; ".join(entries))
    lines.append("")

    lines += ["## 4. Distance shells and shell activity, N7 cells", "", "Probe distance distribution (continuous law; inf = detached), and activity of probe-incident slots by shell (c / j). Shells below 1e-12 mass carry no activity value.", ""]
    body = []
    for family in gte1.FAMILY_ORDER:
        r = results.get(gte1.item_id(7, "W4", family))
        if not r or "held_continuous" not in r:
            continue
        dist = r["held_continuous"]["distance_distribution"]
        sa = r["shell_activity"]
        shells = ", ".join(f"{s}: {m:.2e}" for s, m in dist.items())
        act = ", ".join(f"{s}: {sa['continuous']['shell_activity'].get(s, float('nan')):.3f} / {sa['jump']['shell_activity'].get(s, float('nan')):.3f}" for s in sorted(sa["jump"]["shell_activity"], key=lambda x: (x == "inf", x)))
        body.append([family, shells, act])
    lines += _table(["Family", "Distance distribution", "Activity c / j by shell"], body) + [""]

    lines += ["## 5. Detached-probe counts, N7 cells", "", "Probability that 0, 1, 2, 3 or 4 probes are detached at once (continuous / jump).", ""]
    body = []
    for family in gte1.FAMILY_ORDER:
        p = profiles.get(gte1.item_id(7, "W4", family))
        if p is None:
            continue
        c, j = p["detached_probe_count_distribution_ct"], p["detached_probe_count_distribution_jump"]
        body.append([family] + [f"{c.get(str(k), 0.0):.3f} / {j.get(str(k), 0.0):.3f}" for k in range(5)])
    lines += _table(["Family", "0", "1", "2", "3", "4"], body) + [""]

    lines += ["## 6. Engaged witness load (jump chain, executed events)", "", "Per component: event share / mean engaged witnesses / mean engaged log-weight. The bracket scales log-weights by 1.585 (W3) and 2 (W16).", ""]
    for family, block in t["component_engagement"].items():
        comps = sorted({c for cell in block["cells"].values() for c in cell})
        body = []
        for n, a in CELL_ORDER:
            cell = block["cells"].get(f"N{n}-{a}")
            if cell is None:
                continue
            body.append([f"N{n} {a}"] + [f"{_f(cell[c]['event_share'])} / {_f(cell[c]['mean_witnesses'])} / {_m(cell[c]['mean_log_weight'])}" if c in cell else "—" for c in comps])
        lines += [f"**{family}**", ""] + _table(["Cell"] + comps, body)
        for comp, ratio in block["n7_over_n6"].items():
            lines.append(f"- {comp}: N7/N6 engaged log-weight ratio {_f(ratio['n7_over_n6_mean_log_weight'])} ({ratio['position_against_bracket'].replace('_', ' ')}).")
        lines.append("")

    lines += ["## 7. Calibration: N5 W16 against the published N5 → N6 step (C3)", ""]
    for family, block in t["calibration_n5w16_vs_n6w4"].items():
        lines.append(f"**{family}**{' (clean case)' if block['clean_case'] else ''}: verdict **{block['verdict'].replace('_', ' ')}** ({block.get('comparable', 0)} comparable, {block.get('same_sign', 0)} same sign, of {block['judged_channels']} judged channels).")
        body = [[name, _m(row.get("size_step")), _m(row.get("strength_step")), _f(row.get("ratio")), row["class"].replace("_", " ")] for name, row in block["channels"].items()]
        lines += [""] + _table(["Channel", "N5→N6 (W4)", "W4→W16 (N5)", "ratio", "class"], body) + [""]

    lines += ["## 8. N6 → N7 against strengthening at N6 (C4)", ""]
    for family, block in t["n7_against_n6_strength_response"].items():
        lines.append(f"**{family}** (calibration verdict: {block['calibration_verdict'].replace('_', ' ')}). Class counts: {block['class_counts']}.")
        body = [[name, _m(row.get("size_step")), _m(row.get("strength_step_w3")), _m(row.get("strength_step_w16")), row["class"].replace("_", " ")] for name, row in block["channels"].items()]
        lines += [""] + _table(["Channel", "N6→N7 (W4)", "W4→W3 (N6)", "W4→W16 (N6)", "class"], body) + [""]

    lines += ["## 9. Equal-ratio pairs (C8)", "", "Class-level L1 distance between the stationary laws of the two members of each pair.", ""]
    body = [[k, _f(v["class_l1"])] for k, v in sorted(t["equal_ratio"].items())]
    lines += _table(["Pair (N, alphabet)", "class L1"], body) + [""]

    lines += ["## 10. Geometric reference (C6)", ""]
    body = [[n, _f(v["source_share"]), _f(v["null_attachment_fraction"]), _f(v["null_hub_includes_source"]), _f(v["null_hub_probe_only"])] for n, v in t["geometric_reference"].items()]
    lines += _table(["N", "source share 3/N", "r0", "NULL hub ∋ source", "NULL hub probe-only"], body) + [""]

    lines += ["## 11. Controls and numerical acceptance (Z1–Z6)", ""]
    groups: dict[str, list] = {}
    for key, check in t["frozen_expectations"].items():
        groups.setdefault(key.split("-")[0], []).append((key, check))
    for z, checks in sorted(groups.items()):
        failed = [k for k, c in checks if not c["holds"]]
        lines.append(f"- **{z}:** {len(checks) - len(failed)} of {len(checks)} hold." + (f" Not holding: {', '.join(failed)}." if failed else ""))
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    repo = Path(__file__).resolve().parents[3]
    text = build(repo)
    (repo / OUT).write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
