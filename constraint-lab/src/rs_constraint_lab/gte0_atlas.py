"""Behavioural atlas for GT-E0A and GT-E0B.

Every executed cell appears, including null, saturated and unremarkable
ones. Trajectory selection follows the frozen E0A rule: representative =
lower median of time-mean edges among the cell's samples, atypical = the
sample whose time-mean edges is farthest from the stationary expected edges.
Selected trajectories are copied verbatim from the generated files; each is
replayable from its seed with rs_constraint_lab.gte0a.sample_trajectory.
"""

from __future__ import annotations

import json
from pathlib import Path

ROUNDS = (("round-e0a", "gravity-time/reports/round-e0a-tables.json"), ("round-e0b", "gravity-time/reports/round-e0b-tables.json"))


def select(paths: list[dict], expected_edges: float) -> tuple[int, int]:
    order = sorted(range(len(paths)), key=lambda k: (paths[k]["summary"]["time_mean_edges"], k))
    representative = order[(len(order) - 1) // 2]
    atypical = max(range(len(paths)), key=lambda k: (abs(paths[k]["summary"]["time_mean_edges"] - expected_edges), -k))
    return representative, atypical


def _f(value, digits: int = 3) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        if value != 0 and (abs(value) < 1e-3 or abs(value) >= 1e4):
            return f"{value:.1e}"
        return f"{value:.{digits}f}"
    return str(value)


def build(repo: Path) -> tuple[str, dict]:
    lines = [
        "# GT-E0 behavioural atlas",
        "",
        "Generated by `rs_constraint_lab.gte0_atlas` from the published E0A and E0B tables and the generated trajectory files. Every executed cell is listed. Quantities are exact kernel values; trajectories are illustrative samples (four per cell, 400 events), selected by the frozen rule, and stored in `gt-e0-atlas-trajectories.json`.",
        "",
        "Columns: S reachable states; E expected edges (continuous law); irr irreversible flux fraction; σ entropy production per mean event; A₂ event-order asymmetry (source or class-free frame); A₂ʰ hub-frame asymmetry (E0B only); att attachment fraction (continuous) with null in brackets; det probability the probe is detached; ρ near/far activity ratio (continuous / jump); gap relaxation gap per mean event; L localisation persistence index; cx complex eigenvalue count.",
        "",
    ]
    selected: dict = {}
    for round_id, rel in ROUNDS:
        tables = json.loads((repo / rel).read_text(encoding="utf-8"))
        lines += [f"## {round_id}", "", f"Frozen plan `{tables['frozen_analysis_plan_commit'][:7]}`, payload `{tables['payload_sha256'][:12]}…`.", ""]
        lines.append("| Cell | S | E | irr | σ | A₂ | A₂ʰ | att (null) | det | ρ c / j | gap | L | cx |")
        lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for key in sorted(tables["results"]):
            r = tables["results"][key]
            if r.get("regime") != "recurrent" or "reversibility" not in r:
                lines.append(f"| {key} | {r.get('reachable_states')} | {r.get('regime')} | | | | | | | | | | |")
                continue
            att = det = rho = "—"
            if r["mode"] == "HELD":
                hc = r["held_continuous"]
                att = f"{_f(hc['attachment_fraction'])} ({_f(hc['null_attachment_fraction'])})"
                det = _f(hc["distance_distribution"].get("inf", 0.0))
                sa = r["shell_activity"]
                rho = f"{_f(sa['continuous']['near_far_ratio'])} / {_f(sa['jump']['near_far_ratio'])}"
            hub = _f(r["hub_frame"]["event_order"]["pattern_asymmetry"]) if "hub_frame" in r else "—"
            spec = r.get("spectrum") or {}
            lines.append(
                f"| {key} | {r['reachable_states']} | {_f(r['occupancy_ct']['expected_edges'])} | {_f(r['reversibility']['irreversible_flux_fraction'])} | {_f(r['reversibility']['entropy_production_per_event'])} | {_f(r['event_order']['pattern_asymmetry'])} | {hub} | {att} | {det} | {rho} | {_f(spec.get('relaxation_gap'))} | {_f(r.get('localisation_persistence_index'))} | {_f(spec.get('complex_eigenvalue_count'))} |"
            )
            path = repo / "gravity-time" / "generated" / round_id / "trajectories" / f"{key}.json"
            if path.is_file():
                data = json.loads(path.read_text(encoding="utf-8"))
                paths = data["trajectories"]
                rep, aty = select(paths, r["occupancy_ct"]["expected_edges"])
                selected[f"{round_id}/{key}"] = {"atypical": paths[aty], "atypical_index": aty, "representative": paths[rep], "representative_index": rep, "stationary_expected_edges": r["occupancy_ct"]["expected_edges"], "summaries": [p["summary"] for p in paths]}
        lines.append("")
    lines += ["## Selected trajectories", "", "| Cell | representative (index, time-mean E, distinct states) | atypical (index, time-mean E) | stationary E |", "| --- | --- | --- | --- |"]
    for key, sel in sorted(selected.items()):
        rs, as_ = sel["representative"]["summary"], sel["atypical"]["summary"]
        lines.append(f"| {key} | {sel['representative_index']}, {_f(rs['time_mean_edges'])}, {rs['distinct_states']} | {sel['atypical_index']}, {_f(as_['time_mean_edges'])} | {_f(sel['stationary_expected_edges'])} |")
    lines.append("")
    return "\n".join(lines), selected


def write(repo: Path) -> None:
    text, selected = build(repo)
    (repo / "gravity-time" / "reports" / "gt-e0-atlas.md").write_text(text, encoding="utf-8")
    (repo / "gravity-time" / "reports" / "gt-e0-atlas-trajectories.json").write_text(json.dumps(selected, sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8")
