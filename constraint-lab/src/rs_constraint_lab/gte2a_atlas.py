"""Mechanism atlas for GT Round E2A (GT-P005).

Every item of the frozen plan appears. Values come from the published tables;
nothing is selected or weighted. Exemplars follow the frozen rule (largest
|circulation|, largest |affinity|, largest |circulation| against its affinity).

    python -m rs_constraint_lab.gte2a_atlas
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from rs_constraint_lab import gte2a

OUT = "gravity-time/reports/gt-e2a-atlas.md"


def _f(v, d=3):
    if v is None:
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v != 0 and abs(v) < 1e-3:
            return f"{v:.1e}"
        return f"{v:.{d}f}"
    return str(v)


def _s(v, d=3):
    if v is None:
        return "—"
    if v != 0 and abs(v) < 1e-3:
        return f"{v:+.1e}"
    return f"{v:+.{d}f}"


def _table(header, rows):
    return ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"] + ["| " + " | ".join(r) + " |" for r in rows]


def build(repo: Path, tables: Path | None = None, plan_path: Path | None = None) -> str:
    t = json.loads((tables or repo / gte2a.TABLES_RELPATH).read_text())
    plan = json.loads((plan_path or repo / gte2a.PLAN_RELPATH).read_text())
    R, rows = t["results"], t["cell_rows"]
    L = [
        "# GT-E2A mechanism atlas",
        "",
        f"Generated by `rs_constraint_lab.gte2a_atlas` from `{gte2a.TABLES_RELPATH}` (payload `{t['payload_sha256'][:12]}…`), frozen plan `{t['frozen_analysis_plan_commit'][:7]}` (hash `{t['plan_hash'][:12]}…`). Every item is listed; values are exact-kernel quantities; no cell is ranked.",
        "",
        "Notation: σ = Σ log factor over path-dissolve components − Σ over path-form components (prohibit components excluded); E expected relations (continuous law); irr irreversible flux fraction; partner = partner-frame index (keep the richer partner, release the poorer, signed); handover = E0 four-step index (HELD); A₂ class-free or source-frame event-order asymmetry; A₂ʰ hub frame. Circulation shares are of the adjacent-square |circulation|: aligned with, counter to, or on squares without local affinity. One-way = transitions whose reverse has rate 0.",
        "",
        "## 1. Item records and identities",
        "",
    ]
    body = []
    for it in plan["items"]:
        rec = t["item_records"][it["item_id"]]
        body.append([it["item_id"], it["stratum"], rec["status"], _f(rec["wall_seconds"], 1), _f(rec["peak_rss_mb"], 0), "; ".join(rec["numerical_problems"] or []) or ("structure only" if rec["numerical_problems"] is None else "none")])
    L += _table(["Item", "Stratum", "Status", "Wall s", "Peak MB", "Numerical problems"], body)
    groups: dict[str, list] = {}
    for k, c in t["frozen_expectations"].items():
        groups.setdefault(k.split("-")[0], []).append(c["holds"])
    L += ["", "Identities and acceptance: " + "; ".join(f"**{z}** {sum(v)}/{len(v)}" for z, v in sorted(groups.items())) + ".", ""]

    L += ["## 2. Cell profiles", ""]
    body = []
    for it in plan["items"]:
        r = rows[it["item_id"]]
        if "irreversible_flux_fraction" not in r:
            body.append([it["item_id"], _s(r["sigma"], 2), r["regime"], "—", "—", "—", "—", "—", "—", "—", str(r.get("one_way_transitions")), "—"])
            continue
        body.append([it["item_id"], _s(r["sigma"], 2), _f(r["irreversible_flux_fraction"]), _f(r["expected_edges"], 2), _s(r["partner_index"], 4), _s(r.get("handover_index"), 4), _f(r["event_order_asymmetry"], 4), _f(r["hub_frame_asymmetry"], 4),
                     _f(r["circulation_aligned_share"]), _f(r["circulation_counter_share"]), str(r["one_way_transitions"]), _f(r.get("attachment_fraction_ct"))])
    L += _table(["Cell", "σ", "irr", "E", "partner", "handover", "A₂", "A₂ʰ", "circ aligned", "circ counter", "one-way", "att (c)"], body)
    L += ["", "Structure-only cells: " + "; ".join(f"{k}: {r['class_note']}" for k, r in rows.items() if "irreversible_flux_fraction" not in r) + ".", ""]

    L += ["## 3. Sign of σ against aggregated orientation (C1)", ""]
    body = [[x["cell"], _s(x["sigma"], 2), _s(x["partner_index"], 4), _s(x["handover_index"], 4), _f(x["flux"]), str(x["partner_sign_matches_sigma"]), str(x["handover_sign_matches_sigma"])] for x in t["sigma_sign_table"]]
    L += _table(["Cell", "σ", "partner", "handover", "irr", "partner sign = σ sign", "handover sign = σ sign"], body) + [""]

    L += ["## 4. Squares by role (C2, C5)", "", "Per role: squares, nonzero-affinity squares (positive / negative in the role orientation; HELD attachment/probe squares are oriented probe-probe first), squares with negative far-endpoint degree difference, and circulation per total flux (total / aligned / counter / on zero affinity / signed in role orientation).", ""]
    for it in plan["items"]:
        sq = R[it["item_id"]]["e2a"]["squares"]
        if not sq.get("roles") or "circulation_abs_per_total_flux" not in next(iter(sq["roles"].values())):
            continue
        body = [[role, str(v["squares"]), f"{v['affinity_positive']} / {v['affinity_negative']}", str(v["degree_difference_negative"]), f"{_f(v['circulation_abs_per_total_flux'])} / {_f(v['circulation_aligned_abs_per_total_flux'])} / {_f(v['circulation_counter_abs_per_total_flux'])} / {_f(v['circulation_on_zero_affinity_abs_per_total_flux'])} / {_s(v['circulation_signed_oriented_per_total_flux'])}"] for role, v in sq["roles"].items()]
        L += [f"**{it['item_id']}** — intact {sq['intact_squares']}, broken {sq['broken_squares']}, formula error {_f(sq['formula_max_abs_error'])}", ""] + _table(["Role", "Squares", "A>0 / A<0", "D<0", "circulation: total / aligned / counter / zero-A / signed"], body) + [""]

    L += ["## 5. Matched dissolution (C3)", "", "Per cell and group (support g → target f : relation : action of f): strict enabled / disabled share; mean log rate ratio; normalisation part; mean log jump-probability ratio; passage change within 1 and 8 events; precedence ratio. Mechanisms follow the frozen rule.", ""]
    for it in plan["items"]:
        md = R[it["item_id"]].get("e2a", {}).get("matched_dissolution")
        if not md:
            continue
        body = [[k, f"{_f(g['enabled_share'])} / {_f(g['disabled_share'])}", _s(g["mean_rate_log_ratio"]), _s(g["mean_normalisation_log_ratio"]), _s(g["mean_jump_log_ratio"]), _s(g["passage_delta"]["1"], 4), _s(g["passage_delta"]["8"], 4), _f(g["precedence_ratio"]), ", ".join(g["mechanisms"]) or "none"] for k, g in md.items()]
        L += [f"**{it['item_id']}**", ""] + _table(["Group", "enabled / disabled", "rate", "norm", "jump", "Δpass 1", "Δpass 8", "precedence", "mechanisms"], body) + [""]

    L += ["## 6. Replayable exemplar squares (frozen rule)", "", "States are bit codes over the slot order of `rs_constraint_lab.state.edges(n)`; each square can be replayed from the listed rates.", ""]
    for it in plan["items"]:
        ex = R[it["item_id"]].get("e2a", {}).get("squares", {}).get("exemplars")
        if not ex:
            continue
        parts = []
        for name in ("max_circulation", "max_affinity", "max_counter_circulation"):
            e = ex.get(name)
            if e:
                parts.append(f"{name.replace('_', ' ')}: slots {e['slots']}, role {e['role']}, A {_s(e['affinity'])}, C {_s(e['circulation'], 5)}, D {e['degree_difference_far_endpoints']}, states {e['states']}")
            else:
                parts.append(f"{name.replace('_', ' ')}: none")
        L.append(f"- **{it['item_id']}** — " + "; ".join(parts))
    L.append("")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    repo = Path(__file__).resolve().parents[3]
    text = build(repo)
    (repo / OUT).write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
